import { ChangeDetectionStrategy, Component, computed, inject, input } from '@angular/core';
import { rxResource } from '@angular/core/rxjs-interop';
import { RouterLink } from '@angular/router';
import { Donation } from '@core/models';
import { DonationsApi } from '@core/api/donations-api.service';
import { TranslatePipe } from '@core/i18n/translate.pipe';
import { TranslationService } from '@core/i18n/translation.service';
import { ToastService } from '@core/toast/toast.service';
import { PageHeader } from '@shared/ui/page-header/page-header';
import { StatusPill } from '@shared/ui/status-pill/status-pill';

/** A single donation and its receipt reference — the confirmation a donor
 * lands on after giving, and can return to from their history. */
@Component({
  selector: 'app-donation-detail',
  imports: [RouterLink, TranslatePipe, PageHeader, StatusPill],
  templateUrl: './donation-detail.html',
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class DonationDetail {
  readonly id = input.required<string>();

  private readonly api = inject(DonationsApi);
  private readonly toast = inject(ToastService);
  private readonly translation = inject(TranslationService);

  private readonly resource = rxResource({
    params: () => ({ id: this.id() }),
    stream: ({ params }) => this.api.getDonationDetails(params.id),
  });

  protected readonly loading = computed(() => this.resource.isLoading());
  protected readonly failed = computed(() => this.resource.error() !== undefined);
  protected readonly donation = computed<Donation | null>(() => this.resource.value() ?? null);

  /** Receipt files are not generated by the mock backend. */
  protected downloadReceipt(): void {
    this.toast.success('donations.detail.receiptComingSoon');
  }

  protected money(value: number, currency: string): string {
    return new Intl.NumberFormat(this.translation.locale(), {
      style: 'currency',
      currency,
      maximumFractionDigits: 0,
    }).format(value);
  }

  protected formatDate(iso: string): string {
    return new Intl.DateTimeFormat(this.translation.locale(), {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }).format(new Date(iso));
  }
}
